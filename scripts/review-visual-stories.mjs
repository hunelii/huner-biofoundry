import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.HUNER_PLAYWRIGHT_PATH || 'playwright');
const output = path.resolve('../output/visual-stories-review');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.HUNER_TEST_BROWSER });
const errors = [], checks = [];
const origin = process.env.HUNER_REVIEW_URL || 'http://127.0.0.1:3000';
const inspect = async (page, name) => {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${name} overflow`);
  checks.push(name);
};
const capture = async (page, selector, name) => {
  const element = page.locator(selector).first();
  await element.scrollIntoViewIfNeeded();
  await page.waitForTimeout(150);
  // These are isolated component captures. Fixed navigation is verified in viewport captures.
  await element.screenshot({ path: path.join(output, `${name}.png`), style: '.brand-header, .skip-link, .motion-control { visibility: hidden !important; }' });
};
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/approach/', { waitUntil: 'networkidle' });
  await inspect(page, 'Desktop approach');
  const process = page.locator('.visual-process');
  const at = async fraction => process.evaluate((el, f) => scrollTo({ top: scrollY + el.getBoundingClientRect().top + el.offsetHeight * f - innerHeight * .78, behavior: 'instant' }), fraction);
  await at(.05); await page.waitForTimeout(120); assert.equal(await process.getAttribute('data-step'), '0');
  await at(.65); await page.waitForTimeout(120); assert.equal(await process.getAttribute('data-step'), '3');
  checks.push('Scroll changes the process emphasis');
  await page.getByRole('tab', { name: /02 Cultivate/ }).click();
  assert.match(await page.getByRole('tabpanel').innerText(), /Conditions become/);
  await at(.7); await page.waitForTimeout(120); assert.equal(await process.getAttribute('data-step'), '1');
  checks.push('Manual selection survives subsequent scrolling');
  await page.getByRole('tab', { name: /02 Cultivate/ }).focus();
  await page.keyboard.press('End'); assert.match(await page.getByRole('tabpanel').innerText(), /Develop the finished/);
  await page.keyboard.press('Home'); assert.match(await page.getByRole('tabpanel').innerText(), /Begin with a biological/);
  await page.getByRole('tab', { name: /02 Cultivate/ }).click();
  await capture(page, '.visual-process', 'process-desktop');
  const lens = page.locator('.measurement-lens');
  await lens.getByRole('button', { name: /Target compound/ }).click();
  assert.match(await lens.locator('.measurement-reading').innerText(), /More biomass does not/);
  await capture(page, '.measurement-lens', 'measurement-desktop');
  await page.goto(origin + '/research/', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /02 Modeling/ }).click();
  assert.equal(await page.locator('.research-circuit').getAttribute('data-step'), '1');
  await capture(page, '.research-circuit', 'research-desktop');
  await page.goto(origin + '/applications/', { waitUntil: 'networkidle' });
  await capture(page, '#food', 'application-desktop');
  for (const [name, width, height] of [['phone',390,844],['tablet',820,1180],['small-phone',320,740]]) {
    const context = await browser.newContext({ viewport:{width,height}, hasTouch:true });
    const p = await context.newPage(); p.on('pageerror', e => errors.push(e.message));
    await p.goto(origin+'/approach/', {waitUntil:'networkidle'});
    await inspect(p, `${name} approach`);
    await p.getByRole('tab', { name:/05 Transform/ }).click();
    assert.match(await p.getByRole('tabpanel').innerText(),/Develop the finished/);
    await capture(p,'.visual-process',`process-${name}`);
    await p.locator('.measurement-lens').getByRole('button',{name:/Target compound/}).click();
    await capture(p,'.measurement-lens',`measurement-${name}`);
    await p.goto(origin+'/research/', {waitUntil:'networkidle'}); await inspect(p,`${name} research`);
    await capture(p,'.research-circuit',`research-${name}`);
    await p.goto(origin+'/applications/', {waitUntil:'networkidle'}); await inspect(p,`${name} applications`);
    await context.close();
  }
  await page.emulateMedia({ reducedMotion:'reduce' });
  await page.goto(origin+'/approach/',{waitUntil:'networkidle'});
  await page.locator('.visual-process').scrollIntoViewIfNeeded(); await page.waitForTimeout(100);
  assert.equal(await page.locator('.visual-process').getAttribute('data-motion'),'still');
  assert.equal(await page.locator('.visual-process').getAttribute('data-step'),'0');
  await page.getByRole('tab',{name:/04 Specify/}).click(); assert.match(await page.getByRole('tabpanel').innerText(),/Agree on what crosses/);
  checks.push('Reduced motion is static, controls still work');
  const plain = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const p=await plain.newPage(); await p.goto(origin+'/approach/');
  await p.locator('.measurement-lens .full-sequence summary').click();
  assert.match(await p.locator('.measurement-lens .full-sequence').innerText(),/More biomass does not/);
  checks.push('No-JavaScript complete measurement explanation'); await plain.close();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(origin+'/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.querySelector('.field-layer canvas')?.dataset.status==='spatial');
  await page.evaluate(()=>{const el=document.getElementById('material');scrollTo({top:el.offsetTop+(el.offsetHeight-innerHeight)*.7,behavior:'instant'});});
  await page.waitForFunction(()=>Number(document.querySelector('.field-layer canvas')?.dataset.cellTriangles)>0 && Number(document.getElementById('material')?.dataset.progress)>.69);
  await page.waitForTimeout(2000); await page.getByRole('button',{name:'Pause motion'}).click();
  await page.screenshot({path:path.join(output,'preserved-3d-cell.png')});
  checks.push('Preserved 3D cell rendered');
  await page.locator('#process').scrollIntoViewIfNeeded();
  assert.equal(await page.locator('.visual-process').getAttribute('data-motion'),'still');
  await capture(page,'#process','home-process'); await capture(page,'#research','home-research');
  await page.locator('#food').scrollIntoViewIfNeeded(); await page.screenshot({path:path.join(output,'home-food.png')});
  await inspect(page,'Home with shared motion pause');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({checks,errors,output},null,2));
} finally { await writeFile(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2)); await browser.close(); }
